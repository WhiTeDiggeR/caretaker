#!/usr/bin/env python3
"""Brings a model from a third-party generator (Meshy, Tripo, Rodin, Hunyuan3D, TRELLIS...) into the project (#162).

Runs in Blender's Python (`python3` with the `bpy` module, the same as build_props.py). It imports a GLB/glTF/OBJ/FBX,
joins the meshes, turns it (--rot-y, --rot-x), scales it uniformly to fit the box, puts its lowest point on --floor,
decimates to --max-tris, shrinks the textures to --tex-size and writes a separate glTF plus a wrapper scene:
  loads/characters/<name>/<name>.gltf (+ .bin, textures)
  objects/characters/<name>.tscn        Node3D root, child "Model" = the glTF, no collision (it sits behind glass)
Character models stay out of loads/props: those are generated by our scripts and checked against specs.json.

The default box and floor are the sleeper envelope of the Bowser capsule: origin = capsule socket, floor at y = -0.86,
the figure faces +Z (the window). Usage:
  python3 tools/props/normalize_generated.py SOURCE.glb --name sleeper_bowser_gen [--rot-y 90] [--preview out.png]
Then point the capsule at it: python3 tools/props/make_capsule_assemblies.py --sleeper bowser=sleeper_bowser_gen
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import bpy
from mathutils import Matrix, Vector

REPO = Path(__file__).resolve().parents[2]
BOX = (-1.55, -0.86, -1.05, 1.55, 0.75, 1.05)  # x0 y0 z0 x1 y1 z1 in Godot axes (Y up, +Z front), sleeper_bowser envelope


def _godot_to_blender(v):  # Godot (x, y, z) -> Blender (x, -z, y)
    return Vector((v[0], -v[2], v[1]))


def _import(src: Path) -> None:
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ext = src.suffix.lower()
    if ext in (".glb", ".gltf"):
        bpy.ops.import_scene.gltf(filepath=str(src))
    elif ext == ".obj":
        bpy.ops.wm.obj_import(filepath=str(src))
    elif ext == ".fbx":
        bpy.ops.import_scene.fbx(filepath=str(src))
    else:
        sys.exit(f"unsupported format: {ext}")


def _join() -> bpy.types.Object:
    meshes = [o for o in bpy.context.scene.objects if o.type == "MESH"]
    if not meshes:
        sys.exit("no meshes in the source")
    for o in meshes:  # bake parents/transforms so joining keeps the shape
        mw = o.matrix_world.copy()
        o.parent = None
        o.matrix_world = mw
    for o in list(bpy.context.scene.objects):
        if o.type != "MESH":
            bpy.data.objects.remove(o, do_unlink=True)
    bpy.ops.object.select_all(action="DESELECT")
    for o in meshes:
        o.select_set(True)
    bpy.context.view_layer.objects.active = meshes[0]
    if len(meshes) > 1:
        bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    return obj


def _tris(obj) -> int:
    return sum(len(p.vertices) - 2 for p in obj.data.polygons)


def _fit(obj, box, rot_x: float, rot_y: float, margin: float) -> float:
    # rotations are about Godot axes: X stays X, Godot Y is Blender Z
    obj.data.transform(Matrix.Rotation(math.radians(rot_x), 4, "X"))
    obj.data.transform(Matrix.Rotation(math.radians(rot_y), 4, "Z"))
    lo, hi = _godot_to_blender(box[:3]), _godot_to_blender(box[3:])
    blo = Vector((min(lo.x, hi.x), min(lo.y, hi.y), min(lo.z, hi.z)))
    bhi = Vector((max(lo.x, hi.x), max(lo.y, hi.y), max(lo.z, hi.z)))
    pts = [v.co for v in obj.data.vertices]
    mn = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    mx = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    size, room = mx - mn, (bhi - blo) * (1.0 - margin)
    s = min(room[i] / size[i] for i in range(3) if size[i] > 1e-6)
    centre = (mn + mx) / 2
    target = Vector(((blo.x + bhi.x) / 2, (blo.y + bhi.y) / 2, blo.z))  # centred in plan, standing on the floor
    obj.data.transform(Matrix.Translation(target) @ Matrix.Scale(s, 4) @ Matrix.Translation(-Vector((centre.x, centre.y, mn.z))))
    obj.data.update()
    return s


def _decimate(obj, max_tris: int) -> None:
    n = _tris(obj)
    if n <= max_tris:
        return
    mod = obj.modifiers.new("decimate", "DECIMATE")
    mod.ratio = max_tris / n * 0.98
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.modifier_apply(modifier=mod.name)


def _shrink_textures(size: int) -> None:
    for img in bpy.data.images:
        if img.size[0] > size or img.size[1] > size:
            k = size / max(img.size[0], img.size[1])
            img.scale(max(1, int(img.size[0] * k)), max(1, int(img.size[1] * k)))


def _wrapper(name: str) -> Path:
    out = REPO / "objects" / "characters" / f"{name}.tscn"
    out.parent.mkdir(parents=True, exist_ok=True)
    pascal = "".join(p.capitalize() for p in name.split("_"))
    out.write_text("\n".join([
        "[gd_scene format=3]", "",
        f'[ext_resource type="PackedScene" path="res://loads/characters/{name}/{name}.gltf" id="1_model"]', "",
        f'[node name="{pascal}" type="Node3D"]', "",
        '[node name="Model" parent="." instance=ExtResource("1_model")]', ""]), encoding="utf-8", newline="\n")
    return out


def _preview(obj, path: Path) -> None:
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"  # CPU: works headless without a GPU or EGL
    scene.cycles.samples = 16
    scene.render.resolution_x, scene.render.resolution_y = 1200, 700
    world = bpy.data.worlds.new("w")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs[1].default_value = 0.6
    scene.world = world
    cam = bpy.data.objects.new("cam", bpy.data.cameras.new("cam"))
    scene.collection.objects.link(cam)
    cam.location = _godot_to_blender((1.6, 0.7, 5.6))
    cam.rotation_euler = (math.radians(84), 0, math.radians(18))
    scene.camera = cam
    sun = bpy.data.objects.new("sun", bpy.data.lights.new("sun", "SUN"))
    sun.data.energy = 3.0
    sun.rotation_euler = (math.radians(50), 0, math.radians(30))
    scene.collection.objects.link(sun)
    scene.render.filepath = str(path)
    bpy.ops.render.render(write_still=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path)
    ap.add_argument("--name", required=True, help="output name, e.g. sleeper_bowser_gen")
    ap.add_argument("--box", type=float, nargs=6, default=BOX, metavar=("X0", "Y0", "Z0", "X1", "Y1", "Z1"),
                    help="fit box in Godot axes; the model stands on Y0 (default: Bowser sleeper envelope)")
    ap.add_argument("--rot-y", type=float, default=0.0, help="turn about the vertical axis first, degrees")
    ap.add_argument("--rot-x", type=float, default=0.0, help="tilt about X before that, degrees (Z-up sources: -90)")
    ap.add_argument("--margin", type=float, default=0.02, help="fraction of the box left free")
    ap.add_argument("--max-tris", type=int, default=30000)
    ap.add_argument("--tex-size", type=int, default=1024)
    ap.add_argument("--preview", type=Path, help="also render a quick Cycles preview to this PNG")
    a = ap.parse_args()

    _import(a.source.resolve())
    obj = _join()
    src_tris = _tris(obj)
    s = _fit(obj, a.box, a.rot_x, a.rot_y, a.margin)
    _decimate(obj, a.max_tris)
    _shrink_textures(a.tex_size)
    obj.name = a.name
    out = REPO / "loads" / "characters" / a.name / f"{a.name}.gltf"
    out.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLTF_SEPARATE", use_selection=True,
                              export_image_format="AUTO", export_apply=True)
    wrapper = _wrapper(a.name)
    pts = [obj.matrix_world @ v.co for v in obj.data.vertices]
    lo = [min(p[i] for p in pts) for i in range(3)]
    hi = [max(p[i] for p in pts) for i in range(3)]
    print(f"{a.name}: {src_tris} -> {_tris(obj)} tris, scale {s:.4f}, "
          f"godot x[{lo[0]:.2f}..{hi[0]:.2f}] y[{lo[2]:.2f}..{hi[2]:.2f}] z[{-hi[1]:.2f}..{-lo[1]:.2f}], "
          f"textures {[tuple(i.size) for i in bpy.data.images if i.size[0]]}")
    print(f"wrote {out.relative_to(REPO)} and {wrapper.relative_to(REPO)}")
    if a.preview:
        _preview(obj, a.preview.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
