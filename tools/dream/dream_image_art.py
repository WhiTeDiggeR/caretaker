#!/usr/bin/env python3
"""Relief art of the dream images on the seal rings (#217) from the agreed sketches of #198.

Each sketch ``docs/game_design/dream_glyphs/images/<dream>_<id>_<name>.svg`` draws the image twice
(``#unlit`` — the ring is off, ``#lit`` — the ring is in place). The game draws the glyph itself
(``DreamGlyph``), so the art keeps only the relief of ``#unlit`` without its last group (the muted
skeleton of the glyph) on a round stone medallion that fits the round sockets of the seal rings
(``tools/props/props_dream.py``, Ø 0.84): the relief is scaled by ``FIT`` about the centre so the
figure stays inside the circle; outside the circle the art is transparent. 260 units, ``SIZE`` px.
The glyph then spans ``0.5 * FIT`` of the medallion (``DreamGlyphImage.GLYPH_SHARE``).

  --write   write ``loads/dream_images/<dream>/<id>.svg``
  --check   fail when a committed art file differs from what --write would produce (CI)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKETCHES = ROOT / "docs/game_design/dream_glyphs/images"
OUT = ROOT / "loads/dream_images"
SIZE = 512
TILE = 260
FIT = 0.86
NAME = re.compile(r"^(?P<dream>[a-z]+)_(?P<id>f\d+)_[a-z]+\.svg$")


def _group(text: str, group_id: str) -> str:
    start = text.index(f'<g id="{group_id}">')
    depth = 0
    for match in re.finditer(r"<g\b|</g>", text[start:]):
        depth += 1 if match.group() == "<g" else -1
        if depth == 0:
            return text[start:start + match.end()]
    raise ValueError(f"group {group_id} is not closed")


def _without_last_group(group: str) -> str:
    """The relief: the unlit group without its last child group (the glyph skeleton)."""
    inner = group[group.index(">") + 1:-len("</g>")]
    ends = [m.end() for m in re.finditer(r"</g>", inner)]
    starts = [m.start() for m in re.finditer(r"<g\b", inner)]
    if not starts:
        raise ValueError("no skeleton group")
    last = starts[-1]
    if not ends or ends[-1] <= last:
        raise ValueError("skeleton group is not closed")
    return inner[:last] + inner[ends[-1]:]


def art(sketch: Path) -> str:
    text = sketch.read_text(encoding="utf-8")
    defs = re.search(r'<radialGradient id="stone".*?</radialGradient>', text, re.S)
    if defs is None:
        raise ValueError(f"{sketch.name}: no stone gradient")
    relief = _without_last_group(_group(text, "unlit"))
    # The sketch's own square frame (two rects) gives way to the round medallion.
    relief = re.sub(r'^<rect width="260" height="260" rx="14" fill="#4a4036"/><rect [^>]*fill="url\(#stone\)"/>', "", relief)
    half = TILE / 2
    shift = half * (1 - FIT)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}" width="{SIZE}" height="{SIZE}">\n'
            f"<!-- Generated by tools/dream/dream_image_art.py from {sketch.relative_to(ROOT).as_posix()} (#198, #217). -->\n"
            f"<defs>{defs.group()}</defs>\n"
            f'<circle cx="{half:g}" cy="{half:g}" r="{half:g}" fill="#4a4036"/>'
            f'<circle cx="{half:g}" cy="{half:g}" r="{half - 6:g}" fill="url(#stone)"/>\n'
            f'<g transform="translate({shift:g} {shift:g}) scale({FIT:g})">{relief}</g>\n</svg>\n')


def targets() -> dict[Path, str]:
    result: dict[Path, str] = {}
    for sketch in sorted(SKETCHES.glob("*.svg")):
        match = NAME.match(sketch.name)
        if match:
            result[OUT / match["dream"] / f"{match['id']}.svg"] = art(sketch)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    errors = 0
    for path, text in targets().items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"out of date: {path.relative_to(ROOT).as_posix()}")
            errors += 1
    print(f"dream image art: {len(targets())} files, errors={errors}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
