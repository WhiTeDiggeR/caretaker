#!/usr/bin/env python3
"""Git LFS guard for new binary assets (issue #140).

`.gitattributes` routes binary extensions to LFS. Files that already existed on any `origin` branch when LFS was
switched on stay ordinary git blobs (history is never rewritten); they are listed in the generated section at the
end of `.gitattributes`, which turns the LFS filter off for exactly those paths.

Usage:
  python tools/ci/lfs_check.py                      check: every tracked file with filter=lfs is an LFS pointer
  python tools/ci/lfs_check.py --write-legacy [REF ...]
                                                    regenerate the legacy section from REFs (default: all origin/*)

A failing check means a binary was committed without git-lfs. Fix it with `git lfs install` once, then
`git add --renormalize <file>` and commit.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ATTRS = REPO / ".gitattributes"
BEGIN = "# >>> lfs-legacy: generated by tools/ci/lfs_check.py --write-legacy, do not edit by hand"
END = "# <<< lfs-legacy"
LFS_RULE = re.compile(r"^(\*\.[A-Za-z0-9]+)\s+filter=lfs\b")
POINTER_PREFIX = b"version https://git-lfs.github.com/spec/v1"
POINTER_MAX = 1024
GLOB_CHARS = re.compile(r"[\s*?\[\]\\!#\"]")


def git(*args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["git", *args], cwd=REPO, input=data, capture_output=True, check=True).stdout


def lfs_extensions() -> list[str]:
    exts = []
    for line in ATTRS.read_text(encoding="utf-8").splitlines():
        m = LFS_RULE.match(line)
        if m:
            exts.append(m.group(1)[1:].lower())  # ".png"
    return exts


def write_legacy(refs: list[str]) -> int:
    if not refs:
        refs = [r for r in git("for-each-ref", "--format=%(refname:short)", "refs/remotes/origin").decode().split()
                if r != "origin/HEAD" and r != "origin"]
    exts = tuple(lfs_extensions())
    paths: set[str] = set()
    for ref in refs:
        for p in git("ls-tree", "-r", "-z", "--name-only", ref).decode("utf-8").split("\0"):
            if p.lower().endswith(exts):
                paths.add(p)
    bad = sorted(p for p in paths if GLOB_CHARS.search(p))
    if bad:
        print("paths that cannot be written as literal .gitattributes patterns:\n  " + "\n  ".join(bad))
        return 1
    text = ATTRS.read_text(encoding="utf-8")
    head = text.split(BEGIN)[0].rstrip("\n")
    body = "\n".join(f"/{p} !filter !diff !merge" for p in sorted(paths))
    ATTRS.write_text(f"{head}\n\n{BEGIN}\n# Pre-LFS binaries from {len(refs)} refs stay regular blobs.\n{body}\n{END}\n",
                     encoding="utf-8")
    print(f"legacy section: {len(paths)} files from {len(refs)} refs")
    return 0


def check() -> int:
    files = [p for p in git("ls-files", "-z").decode("utf-8").split("\0") if p]
    out = git("check-attr", "-z", "--stdin", "filter", data="\0".join(files).encode()).decode("utf-8").split("\0")
    lfs = [out[i] for i in range(0, len(out) - 2, 3) if out[i + 2] == "lfs"]
    # Index blobs, not the working tree: a checkout without smudge holds pointers either way.
    stage = {}
    for line in git("ls-files", "-s", "-z", "--", *lfs).decode("utf-8").split("\0") if lfs else []:
        if line:
            meta, path = line.split("\t", 1)
            stage[path] = meta.split()[1]
    raw = []
    if stage:
        batch = git("cat-file", "--batch", data="\n".join(stage.values()).encode() + b"\n")
        pos = 0
        for path, oid in stage.items():
            header_end = batch.index(b"\n", pos)
            size = int(batch[pos:header_end].split()[2])
            content = batch[header_end + 1:header_end + 1 + size]
            pos = header_end + 1 + size + 1
            if size > POINTER_MAX or not content.startswith(POINTER_PREFIX):
                raw.append((path, size))
    legacy = ATTRS.read_text(encoding="utf-8").count(" !filter !diff !merge")
    if raw:
        print(f"{len(raw)} file(s) match an LFS rule in .gitattributes but were committed as regular blobs:")
        for path, size in raw[:40]:
            print(f"  {path} ({size / 1048576:.1f} MB)")
        print("Fix: `git lfs install` (once), then `git add --renormalize <file>` and commit. See docs/LFS.md.")
        return 1
    print(f"LFS_CHECK lfs_files={len(lfs)} legacy_entries={legacy} raw=0")
    return 0


def main(argv: list[str]) -> int:
    if argv[:1] == ["--write-legacy"]:
        return write_legacy(argv[1:])
    if argv:
        print(__doc__)
        return 2
    return check()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
